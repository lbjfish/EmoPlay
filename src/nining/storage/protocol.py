"""Backend protocol shared by game-state orchestration code."""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class StorageBackend(Protocol):
    """Portable persistence contract.

    Return values are detached dictionaries. Immutable append methods are
    idempotent only when the complete record is identical.
    """

    backend_name: str
    fallback_reason: str | None

    def close(self) -> None: ...

    def create_playthrough(self, **values: Any) -> dict[str, Any]: ...
    def get_playthrough(self, playthrough_id: str) -> dict[str, Any]: ...
    def list_playthroughs(self) -> list[dict[str, Any]]: ...

    def create_branch(self, **values: Any) -> dict[str, Any]: ...
    def get_branch(self, playthrough_id: str, branch_id: str) -> dict[str, Any]: ...
    def list_branches(self, playthrough_id: str) -> list[dict[str, Any]]: ...

    def append_story_event(self, **values: Any) -> dict[str, Any]: ...
    def list_story_events(
        self, playthrough_id: str, branch_id: str, *, include_ancestry: bool = False
    ) -> list[dict[str, Any]]: ...

    def create_checkpoint(self, **values: Any) -> dict[str, Any]: ...
    def get_checkpoint(
        self, playthrough_id: str, checkpoint_id: str
    ) -> dict[str, Any]: ...
    def list_checkpoints(
        self, playthrough_id: str, *, branch_id: str | None = None
    ) -> list[dict[str, Any]]: ...

    def set_head(self, **values: Any) -> dict[str, Any]: ...
    def get_head(self, playthrough_id: str) -> dict[str, Any]: ...
    def save_slot(self, **values: Any) -> dict[str, Any]: ...
    def get_save_slot(self, playthrough_id: str, slot_name: str) -> dict[str, Any]: ...
    def list_save_slots(self, playthrough_id: str) -> list[dict[str, Any]]: ...

    def select_feature(self, **values: Any) -> dict[str, Any]: ...
    def list_feature_selections(
        self, playthrough_id: str, *, branch_id: str | None = None
    ) -> list[dict[str, Any]]: ...

    def begin_run(self, **values: Any) -> dict[str, Any]: ...
    def finish_run(self, run_id: str, **values: Any) -> dict[str, Any]: ...
    def get_run(self, run_id: str) -> dict[str, Any]: ...
    def list_runs(
        self, playthrough_id: str | None = None, *, branch_id: str | None = None
    ) -> list[dict[str, Any]]: ...
    def record_provider_call(self, **values: Any) -> dict[str, Any]: ...
    def list_provider_calls(
        self, playthrough_id: str | None = None, *, branch_id: str | None = None
    ) -> list[dict[str, Any]]: ...
    def register_asset(self, **values: Any) -> dict[str, Any]: ...
    def list_assets(
        self, playthrough_id: str | None = None, *, branch_id: str | None = None
    ) -> list[dict[str, Any]]: ...
    def record_decision(self, **values: Any) -> dict[str, Any]: ...
    def list_decisions(
        self, playthrough_id: str | None = None, *, branch_id: str | None = None
    ) -> list[dict[str, Any]]: ...

    def export_snapshot(self) -> dict[str, Any]: ...
    def import_snapshot(self, snapshot: Mapping[str, Any]) -> None: ...
    def integrity_check(self) -> dict[str, Any]: ...
